    public static bool IsReservedSlug(string? slug)
    {
        if (string.IsNullOrWhiteSpace(slug))
        {
            return false;
        }

        return ReservedSlugs.Contains(slug.Trim());
    }

    public static string GetCultureTagLabel(string slug)
    {
        if (!string.IsNullOrWhiteSpace(slug) &&
            CultureTagLabelsBySlug.TryGetValue(slug.Trim().ToLowerInvariant(), out var label))
        {
            return label;
        }

        return slug;
    }

    public static string GenerateSlugFromName(string? name)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            return string.Empty;
        }

        var normalizedFormD = name.Trim().Normalize(NormalizationForm.FormD);
        var sb = new StringBuilder(normalizedFormD.Length);
        var previousWasHyphen = false;

        for (var i = 0; i < normalizedFormD.Length; i++)
        {
            var ch = normalizedFormD[i];
            var category = CharUnicodeInfo.GetUnicodeCategory(ch);
            if (category == UnicodeCategory.NonSpacingMark)
            {
                continue;
            }

            if (ch is >= 'A' and <= 'Z')
            {
                sb.Append((char)(ch + ('a' - 'A')));
                previousWasHyphen = false;
            }
            else if ((ch is >= 'a' and <= 'z') || (ch is >= '0' and <= '9'))
            {
                sb.Append(ch);
                previousWasHyphen = false;
            }
            else if (ch is '&' or '+')
            {
                if (sb.Length > 0 && !previousWasHyphen)
                {
                    sb.Append('-');
                }

                sb.Append("and-");
                previousWasHyphen = true;
            }
            else
            {
                if (sb.Length > 0 && !previousWasHyphen)
                {
                    sb.Append('-');
                    previousWasHyphen = true;
                }
            }
        }

        while (sb.Length > 0 && sb[^1] == '-')
        {
            sb.Length--;
        }

        if (sb.Length > MaxAutoGeneratedSlugLength)
        {
            sb.Length = MaxAutoGeneratedSlugLength;
            while (sb.Length > 0 && sb[^1] == '-')
            {
                sb.Length--;
            }
        }

        var candidate = sb.ToString();
        if (candidate.Length == 1)
        {
            candidate = $"{candidate}-studio";
        }
        else if (candidate.Length >= MinStudioSlugLength && IsReservedSlug(candidate))
        {
            candidate = $"{candidate}-studio";
        }

        return candidate;
    }

    public static bool TryNormalizeSlug(
        string? rawSlug,
        out string normalizedSlug,
        out string? errorMessage)
    {
        normalizedSlug = string.Empty;
        errorMessage = null;

        if (string.IsNullOrWhiteSpace(rawSlug))
        {
            errorMessage = "Studio URL slug is required.";
            return false;
        }

        var trimmed = rawSlug.Trim().ToLowerInvariant();
        if (trimmed.Length < MinStudioSlugLength || trimmed.Length > MaxStudioSlugLength)
        {
            errorMessage = $"Studio URL slug must be between {MinStudioSlugLength} and {MaxStudioSlugLength} characters.";
            return false;
        }

        if (trimmed[0] == '-' || trimmed[^1] == '-')
        {
            errorMessage = "Studio URL slug cannot start or end with a hyphen.";
            return false;
        }

        for (var i = 0; i < trimmed.Length; i++)
        {
            var ch = trimmed[i];
            var isLowerOrDigit = (ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9');
            if (isLowerOrDigit)
            {
                continue;
            }

            if (ch == '-')
            {
                if (i > 0 && trimmed[i - 1] == '-')
                {
                    errorMessage = "Studio URL slug cannot contain consecutive hyphens ('--').";
                    return false;
                }

                continue;
            }

            errorMessage = "Studio URL slug can only contain lowercase letters (a-z), numbers (0-9), and single hyphens.";
            return false;
        }

        if (IsReservedSlug(trimmed))
        {
            errorMessage = $"The URL slug '{trimmed}' is reserved. Choose a more specific studio slug (for example, '{trimmed}-games').";
            return false;
        }

        normalizedSlug = trimmed;
        return true;
    }

    /// <summary>
    /// Validates and normalizes an optional Indian GSTIN against Blueprint v2.0 Section 5:
    /// <c>^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$</c>.
    /// </summary>
    public static bool TryNormalizeGstin(
        string? rawGstin,
        out string? normalizedGstin,
        out string? errorMessage)
    {
        normalizedGstin = null;
        errorMessage = null;

        if (string.IsNullOrWhiteSpace(rawGstin))
        {
            return true;
        }

        var compactBuilder = new StringBuilder(16);
        var trimmed = rawGstin.Trim();
        for (var i = 0; i < trimmed.Length; i++)
        {
            var ch = trimmed[i];
            if (ch is ' ' or '-')
            {
                continue;
            }

            compactBuilder.Append(char.ToUpperInvariant(ch));
        }

        var candidate = compactBuilder.ToString();
        if (candidate.Length != 15 || !MatchesGstinPattern(candidate))
        {
            errorMessage = "Enter a valid 15-character Indian GSTIN (for example, 29ABCDE1234F1Z5), or leave it blank.";
            return false;
        }

        normalizedGstin = candidate;
        return true;
    }

    public static bool TryNormalizeCultureTags(
        IEnumerable<string>? rawTags,
        out string[] normalizedTags,
        out string? errorMessage)
    {
        errorMessage = null;

        if (rawTags is null)
        {
            normalizedTags = [];
            return true;
        }

        var result = new List<string>(MaxCultureTags);
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var rawTag in rawTags)
        {
            if (string.IsNullOrWhiteSpace(rawTag))
            {
                continue;
            }

            var normalized = rawTag.Trim().ToLowerInvariant();
            if (!CultureTagLabelsBySlug.ContainsKey(normalized))
            {
                errorMessage = $"Unsupported culture tag '{rawTag.Trim()}'. Select tags from the supported studio culture list.";
                normalizedTags = [];
                return false;
            }

            if (seen.Add(normalized))
            {
                result.Add(normalized);
            }
        }

        if (result.Count > MaxCultureTags)
        {
            errorMessage = $"Select up to {MaxCultureTags} culture tags.";
            normalizedTags = [];
            return false;
        }

        normalizedTags = result.ToArray();
        return true;
    }

    public static string? ExtractCompanyDomainFromWebsite(string? normalizedHttpsWebsite)
    {
        if (string.IsNullOrWhiteSpace(normalizedHttpsWebsite))
        {
            return null;
        }

        if (!Uri.TryCreate(normalizedHttpsWebsite.Trim(), UriKind.Absolute, out var uri))
        {
            return null;
        }

        var host = uri.IdnHost.Trim().ToLowerInvariant();
        if (host.StartsWith("www.", StringComparison.Ordinal))
        {
            var stripped = host[4..];
            if (stripped.Contains('.', StringComparison.Ordinal))
            {
                host = stripped;
            }
        }

        return string.IsNullOrWhiteSpace(host) ? null : host;
    }

