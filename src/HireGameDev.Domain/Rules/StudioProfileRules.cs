    /// <summary>
    /// ADR-019 Decision #3: Identity-critical fields (<c>Name</c>, <c>Slug</c>, <c>Gstin</c>) lock
    /// while verification is <c>pending</c> or <c>verified</c> to prevent post-verification brand impersonation.
