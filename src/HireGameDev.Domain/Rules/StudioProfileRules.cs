    public static bool IsIdentityFieldLocked(StudioVerificationStatus status) =>
        status is StudioVerificationStatus.Pending or StudioVerificationStatus.Verified;

    public static bool CanEditIdentityFields(StudioMemberRole role, StudioVerificationStatus status) =>
        CanEditProfile(role) && !IsIdentityFieldLocked(status);

    /// <summary>
    /// ADR-018 Decision #4: Studio URL slug is editable by the owner while unverified or rejected,
    /// and locked once verification is pending or verified so verified URLs and brand checks remain stable.
    /// </summary>
    public static bool CanEditSlug(StudioMemberRole role, StudioVerificationStatus status) =>
        role == StudioMemberRole.Owner && !IsIdentityFieldLocked(status);

    /// <summary>
    /// ADR-018 Decision #1: Public <c>/studios/{slug}</c> pages render to anonymous visitors only when
    /// <see cref="StudioVerificationStatus.Verified"/>; signed-in studio members and Admins can preview anytime.
    /// </summary>
    public static bool CanViewPublicStudioPage(
        StudioVerificationStatus status,
        bool isDeleted,
        bool isMemberOfStudio,
        bool isAdmin)
    {
        if (isDeleted)
        {
            return false;
        }

        return status == StudioVerificationStatus.Verified || isMemberOfStudio || isAdmin;
    }

    private static bool MatchesGstinPattern(string s)
    {
        // ^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$
        return IsAsciiDigit(s[0]) &&
               IsAsciiDigit(s[1]) &&
               IsAsciiUpper(s[2]) &&
               IsAsciiUpper(s[3]) &&
               IsAsciiUpper(s[4]) &&
               IsAsciiUpper(s[5]) &&
               IsAsciiUpper(s[6]) &&
               IsAsciiDigit(s[7]) &&
               IsAsciiDigit(s[8]) &&
               IsAsciiDigit(s[9]) &&
               IsAsciiDigit(s[10]) &&
               IsAsciiUpper(s[11]) &&
               IsNonZeroDigitOrAsciiUpper(s[12]) &&
               s[13] == 'Z' &&
               IsDigitOrAsciiUpper(s[14]);
    }

    private static bool IsAsciiDigit(char c) => c is >= '0' and <= '9';

    private static bool IsAsciiUpper(char c) => c is >= 'A' and <= 'Z';

    private static bool IsDigitOrAsciiUpper(char c) => IsAsciiDigit(c) || IsAsciiUpper(c);

    private static bool IsNonZeroDigitOrAsciiUpper(char c) => (c is >= '1' and <= '9') || IsAsciiUpper(c);
}
